package publishing

import (
	"fmt"
	"strings"
)

// Workflow is generated from the same allowlist and pins used by the builders.
func Workflow(recipes []Recipe) string {
	var b strings.Builder
	b.WriteString(`# Generated by quasidock-publish generate; do not edit recipe jobs by hand.
name: Publish images
on:
  workflow_dispatch:
permissions:
  contents: read
concurrency:
  group: publish-ghcr-quasidock
  cancel-in-progress: false
jobs:
  prepare:
    if: github.repository == 'quasidock/quasidock' && github.ref == 'refs/heads/dev'
    runs-on: windows-2025
    timeout-minutes: 15
    steps:
      - uses: actions/checkout@v7
        with:
          persist-credentials: false
      - uses: actions/setup-go@v6
        with:
          go-version-file: go.mod
      - name: Validate signing setup and generated workflow
        shell: bash
        run: |
          grep -q -- '-----BEGIN PUBLIC KEY-----' internal/trust/quasidock.pub || { echo 'Configure the Quasidock public key first; see docs/publishing.md'; exit 1; }
          go run ./cmd/quasidock-publish generate --check
      - uses: sigstore/cosign-installer@v4.1.0
        with:
          cosign-release: v3.1.4
      - name: Verify signing secrets before building applications
        shell: bash
        env:
          COSIGN_PRIVATE_KEY: ${{ secrets.COSIGN_PRIVATE_KEY }}
          COSIGN_PASSWORD: ${{ secrets.COSIGN_PASSWORD }}
        run: |
          key="$RUNNER_TEMP/quasidock-preflight.key"
          public="$RUNNER_TEMP/quasidock-preflight.pub"
          trap 'rm -f "$key" "$public"' EXIT
          test -n "$COSIGN_PRIVATE_KEY" && test -n "$COSIGN_PASSWORD"
          printf '%s\n' "$COSIGN_PRIVATE_KEY" >"$key"
          unset COSIGN_PRIVATE_KEY
          cosign public-key --key "$(cygpath -w "$key")" >"$public"
          diff -u <(tr -d '\r' <internal/trust/quasidock.pub) <(tr -d '\r' <"$public")
      - name: Unit and fixture integration tests
        run: go test -count=1 ./...
      - name: Candidate staging contract
        shell: bash
        run: bash tests/publish.sh
      - name: Build programs once for this run
        run: |
          go run ./scripts/build.go --strip
          go build -trimpath -o out/bin/quasidock-publish.exe ./cmd/quasidock-publish
          Copy-Item -LiteralPath (Get-Command cosign).Source -Destination out/bin/cosign.exe
      - uses: actions/upload-artifact@v7
        with:
          name: publish-programs
          path: out/bin/*.exe
          overwrite: true
          retention-days: 14
`)
	byID := map[string]Recipe{}
	for _, r := range recipes {
		byID[r.ID] = r
	}
	for _, r := range recipes {
		fmt.Fprintf(&b, "  %s:\n    needs: [prepare", r.Job())
		for _, p := range r.Pins {
			fmt.Fprintf(&b, ", %s", byID[p.ID].Job())
		}
		fmt.Fprintf(&b, "]\n    uses: ./.github/workflows/publish-image.yml\n    permissions:\n      actions: read\n      contents: read\n      packages: write\n    with:\n      recipe: %s\n    secrets: inherit\n", r.File)
	}
	b.WriteString("  finish:\n    needs: [prepare")
	for _, r := range recipes {
		fmt.Fprintf(&b, ", %s", r.Job())
	}
	b.WriteString(`]
    runs-on: windows-2025
    timeout-minutes: 45
    permissions:
      contents: read
      packages: write
    env:
      QUASIDOCK_REGISTRY: ghcr.io/quasidock/quasidock
    steps:
      - uses: actions/checkout@v7
        with:
          persist-credentials: false
      - name: Isolate the publishing store
        run: '"QUASIDOCK_HOME=$env:RUNNER_TEMP\publish-store" >> $env:GITHUB_ENV'
      - uses: actions/download-artifact@v8
        with:
          name: publish-programs
          path: out/bin
      - uses: actions/download-artifact@v8
        with:
          pattern: publish-report-*
          path: out/reports
          merge-multiple: true
      - name: Collect verified results and pin patch
        shell: bash
        run: out/bin/quasidock-publish.exe collect out/reports out/publishing
      - name: Publish candidate catalog
        shell: bash
        env:
          QUASIDOCK_REGISTRY_USERNAME: ${{ github.actor }}
          QUASIDOCK_REGISTRY_PASSWORD: ${{ github.token }}
        run: out/bin/quasidock-publish.exe catalog out/reports "ci-$GITHUB_RUN_ID"
      - name: Verify anonymous access before promotion
        shell: bash
        run: out/bin/quasidock-publish.exe verify out/reports
      - name: Promote exact verified digests; catalog last
        shell: bash
        env:
          QUASIDOCK_REGISTRY_USERNAME: ${{ github.actor }}
          QUASIDOCK_REGISTRY_PASSWORD: ${{ github.token }}
        run: out/bin/quasidock-publish.exe promote out/reports
      - name: Verify final tags, pins, and searchable catalog anonymously
        shell: bash
        run: |
          out/bin/quasidock-publish.exe verify-release out/reports
          bash scripts/check-pins.sh out/publishing/recipes/*.json
          out/bin/quasidock.exe search
      - name: Keep result report even if promotion fails
        if: always()
        uses: actions/upload-artifact@v7
        with:
          name: publishing-result
          path: out/publishing
          overwrite: true
          if-no-files-found: ignore
          retention-days: 30
      - name: Run summary
        if: always()
        shell: bash
        run: test ! -f out/publishing/summary.md || cat out/publishing/summary.md >> "$GITHUB_STEP_SUMMARY"
`)
	return b.String()
}
