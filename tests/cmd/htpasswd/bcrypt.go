func (bf *bfKey) encrypt(l, r uint32) (uint32, uint32) {
	for i := 0; i < 16; i += 2 {
		l ^= bf.p[i]
		r ^= (((bf.s[0][byte(l>>24)] + bf.s[1][byte(l>>16)]) ^ bf.s[2][byte(l>>8)]) + bf.s[3][byte(l)]) ^ bf.p[i+1]
		l ^= (((bf.s[0][byte(r>>24)] + bf.s[1][byte(r>>16)]) ^ bf.s[2][byte(r>>8)]) + bf.s[3][byte(r)])
	}
	l ^= bf.p[16]
	r ^= bf.p[17]
	return r, l
}

func (bf *bfKey) expandKey(key []byte) {
	var j int
	for i := 0; i < 18; i++ {
		var data uint32
		for k := 0; k < 4; k++ {
			data = (data << 8) | uint32(key[j])
			j++
			if j >= len(key) {
				j = 0
			}
		}
		bf.p[i] ^= data
	}
	var l, r uint32
	for i := 0; i < 18; i += 2 {
		l, r = bf.encrypt(l, r)
		bf.p[i] = l
		bf.p[i+1] = r
	}
	for i := 0; i < 4; i++ {
		for k := 0; k < 256; k += 2 {
			l, r = bf.encrypt(l, r)
			bf.s[i][k] = l
			bf.s[i][k+1] = r
		}
	}
}

func (bf *bfKey) eksExpandKey(password, salt []byte) {
	var j, s int
	for i := 0; i < 18; i++ {
		var data uint32
		for k := 0; k < 4; k++ {
			data = (data << 8) | uint32(password[j])
			j++
			if j >= len(password) {
				j = 0
			}
		}
		bf.p[i] ^= data
	}
	var l, r uint32
	for i := 0; i < 18; i += 2 {
		var sDataL, sDataR uint32
		for k := 0; k < 4; k++ {
			sDataL = (sDataL << 8) | uint32(salt[s])
			s = (s + 1) % len(salt)
		}
		for k := 0; k < 4; k++ {
			sDataR = (sDataR << 8) | uint32(salt[s])
			s = (s + 1) % len(salt)
		}
		l ^= sDataL
		r ^= sDataR
		l, r = bf.encrypt(l, r)
		bf.p[i] = l
		bf.p[i+1] = r
	}
	for i := 0; i < 4; i++ {
		for k := 0; k < 256; k += 2 {
			var sDataL, sDataR uint32
			for m := 0; m < 4; m++ {
				sDataL = (sDataL << 8) | uint32(salt[s])
				s = (s + 1) % len(salt)
			}
			for m := 0; m < 4; m++ {
				sDataR = (sDataR << 8) | uint32(salt[s])
				s = (s + 1) % len(salt)
			}
			l ^= sDataL
			r ^= sDataR
			l, r = bf.encrypt(l, r)
			bf.s[i][k] = l
			bf.s[i][k+1] = r
		}
	}
}

func newBf() *bfKey {
	bf := &bfKey{
		p: bfPInit,
		s: bfSInit,
	}
	return bf
}

const bcryptBase64 = "./ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"

func encodeBcryptBase64(src []byte) string {
	var dst []byte
	n := len(src)
	for i := 0; i < n; {
		c1 := uint32(src[i])
		i++
		dst = append(dst, bcryptBase64[c1>>2])
		c1 = (c1 & 0x03) << 4
		if i >= n {
			dst = append(dst, bcryptBase64[c1])
			break
		}
		c2 := uint32(src[i])
		i++
		c1 |= c2 >> 4
		dst = append(dst, bcryptBase64[c1])
		c1 = (c2 & 0x0f) << 2
		if i >= n {
			dst = append(dst, bcryptBase64[c1])
			break
		}
		c3 := uint32(src[i])
		i++
		c1 |= c3 >> 6
		dst = append(dst, bcryptBase64[c1])
		dst = append(dst, bcryptBase64[c3&0x3f])
	}
	return string(dst)
}

func bcryptHash(password []byte, cost int) (string, error) {
	if cost < 4 || cost > 31 {
		cost = 10
	}
	salt := make([]byte, 16)
	if _, err := io.ReadFull(rand.Reader, salt); err != nil {
		return "", err
	}

	// Password null-terminated, truncated to 72 bytes
	pass := append(password, 0)
	if len(pass) > 72 {
		pass = pass[:72]
	}

	bf := newBf()
	bf.eksExpandKey(pass, salt)
	rounds := 1 << cost
	for i := 0; i < rounds; i++ {
		bf.expandKey(pass)
		bf.expandKey(salt)
	}

	// Encrypt magic text "OrpheanBeholderScryDoubt" (24 bytes)
	magic := []byte("OrpheanBeholderScryDoubt")
	cwords := make([]uint32, 6)
	for i := 0; i < 6; i++ {
		cwords[i] = binary.BigEndian.Uint32(magic[i*4 : (i+1)*4])
	}
	for i := 0; i < 64; i++ {
		for j := 0; j < 6; j += 2 {
			cwords[j], cwords[j+1] = bf.encrypt(cwords[j], cwords[j+1])
		}
	}

	cipherBytes := make([]byte, 23)
	outBuf := make([]byte, 24)
	for i := 0; i < 6; i++ {
		binary.BigEndian.PutUint32(outBuf[i*4:], cwords[i])
	}
	copy(cipherBytes, outBuf[:23])

	saltStr := encodeBcryptBase64(salt)
	hashStr := encodeBcryptBase64(cipherBytes)

	return fmt.Sprintf("$2a$%02d$%s%s", cost, saltStr, hashStr), nil
}
